import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import crypto from 'node:crypto';
const read=p=>fs.readFileSync(p,'utf8');
const dead=['matte-premium-v57.css','matte-director-v58.css','matte-polish-v59.css','sculptural-restore-v61.css','matte-finish-v62.css','touch-depth-v72.js'];
for(const name of dead)assert.ok(!fs.existsSync('www/'+name),'Legacy unused runtime file still present: '+name);
const head=read('www/index.html');
const motion=read('www/sculpted-motion-v77.js');
const cssSources=['r78-header.css','r78-hero.css','r78-details.css','r79-visual-qa.css'];
for(const name of cssSources)assert.ok(fs.existsSync('www/'+name),'Retained editable source CSS missing: '+name);
assert.match(motion,/r80-theme\.css/,'Runtime must load only one current design sheet');
for(const name of cssSources)assert.ok(!motion.includes("'"+name+"'"),'Runtime still attaches fragmented CSS layer: '+name);
assert.match(motion,/r78-runtime\.js/,'Dashboard DOM enhancement still enabled');
assert.match(motion,/RashodyGrandMotion|RashodySculptedMotion|duration:790/,'Current sculpted animation retained');
assert.match(head,/src="premium-motion-v73\.js"/);
assert.match(head,/src="premium-motion-v76\.js"/);
assert.match(head,/src="sculpted-motion-v77\.js"/);
assert.match(head,/function persist\(\)/);
assert.match(head,/function daySummaryRing\(/);
assert.match(read('native/FinanceStoragePlugin.java'),/class FinanceStoragePlugin/);
execFileSync('node',['scripts/bundle-runtime-theme-v80.mjs'],{stdio:'inherit'});
const output=read('www/r80-theme.css');
const input=cssSources.map(name=>read('www/'+name));
for(const source of input)assert.ok(output.includes(source),'Missing source rules in generated theme');
for(let i=1;i<input.length;i++)assert.ok(output.indexOf(input[i-1])<output.indexOf(input[i]),'CSS cascade order changed');
assert.ok(output.includes('.fancy-empty::before'),'Empty-state styling lost');
assert.ok(output.includes('.day-donut-sector'),'Chart styling lost');
assert.ok(output.includes('.mobile-nav'),'Navigation styling lost');
const sha=crypto.createHash('sha256').update(output).digest('hex');
assert.ok(sha.length===64);
execFileSync('node',['--check','www/sculpted-motion-v77.js'],{stdio:'inherit'});
execFileSync('node',['--check','www/r78-runtime.js'],{stdio:'inherit'});
console.log('OK: 6 dead runtime files removed, one bundled skin, no change to expense code or active motion; css sha256 '+sha);
