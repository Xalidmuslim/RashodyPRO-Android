import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('www/index.html','utf8');
const css=fs.readFileSync('www/deep-matte.css','utf8');
const start=css.indexOf('/* v5.3: category choices');
assert.ok(start>=0,'Missing animated selection surface');
const finish=css.slice(start);
assert.match(finish,/\.category-picker \.cat-choice::before\s*\{/, 'Compositor overlay should exist');
assert.match(finish,/transition:\s*opacity\s+\.24s/, 'Selected category must crossfade rather than jump');
assert.match(finish,/\.cat-choice\.active::before\s*\{[\s\S]*?opacity:\s*1/, 'Active overlay must be visible');
assert.match(finish,/\.cat-choice\s*>\s*\*/, 'Keep category content above overlay');
assert.match(finish,/\.cat-choice:focus-visible/, 'Preserve keyboard navigation');
assert.match(finish,/prefers-reduced-motion:\s*reduce/, 'Honor reduced motion');
assert.ok(!/transition:[^;]*(?:box-shadow|filter)/.test(finish),'Never animate expensive shadows');
assert.ok(!/(?:linear|radial)-gradient\s*\(/.test(finish),'No glossy gradients');
assert.match(finish,/#txSelectedCategory\s*\{[\s\S]*?text-overflow:\s*ellipsis/, 'Long category names must not reflow the header');
assert.match(html,/if\(btn\.dataset\.txCategory&&draft\)\{[\s\S]*?if\(draft\.category===next\)return/, 'Repeat selection should not redraw');
assert.match(html,/chosen\.animate\(\[\{opacity:\.45/, 'Selected name should change smoothly');
assert.match(html,/aria-pressed.*String\(active\)/, 'Selected category must remain accessible');
assert.match(html,/Расходы PRO 5\.\d+(?:\.\d+)? · Deep Matte/, 'UI build marker must identify installed version');
console.log('OK: animated category selection, reduced motion, readable name, stable layout');
